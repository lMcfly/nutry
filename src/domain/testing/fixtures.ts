type Macros = readonly [proteinG: number, carbsG: number, fatG: number, fiberG: number];

/** Construit une recette ; kcal recalculées depuis les macros (4/4/9/2). */
export function makeRecipe(
  partial: Partial<Omit<Recipe, 'nutritionPerServing'>> & Pick<Recipe, 'id'> & { macros?: Macros },
): Recipe {
  const [proteinG, carbsG, fatG, fiberG] = partial.macros ?? [25, 50, 15, 8];
  // eslint-disable-next-line @typescript-eslint/no-unused-vars
  const { macros, ...rest } = partial;
  return {
    name: partial.id,
    level: 'simple',
    prepMinutes: 5,
    cookMinutes: 10,
    servings: 2,
    diets: ALL_DIETS,
    allergens: [],
    mainProtein: 'legumineuses',
    seasons: ['printemps', 'ete', 'automne', 'hiver'],
    ingredients: [
      ing('lentilles', 150, 'g', 'epicerie'),
      ing('carotte', 2, 'piece', 'fruits-legumes'),
    ],
    steps: ['Cuisiner.'],
    plateBalance: { vegetables: 0.5, proteins: 0.25, starches: 0.25 },
    tags: [],
    ...rest,
    nutritionPerServing: {
      kcal: Math.round(4 * proteinG + 4 * carbsG + 9 * fatG + 2 * fiberG),
      proteinG,
      carbsG,
      fatG,
      fiberG,
    },
  };
}

